def permute(value, table, width):
    """Bảng DES đánh số bit từ 1, tính từ MSB."""
    result = 0
    for position in table:
        result = (result << 1) | ((value >> (width - position)) & 1)
    return result

def rol28(x, n):
    return ((x << n) | (x >> (28-n))) & 0xFFFFFFF

def key_schedule(key, log=lambda _: None):
    k56 = permute(key, PC1, 64)
    c, d = k56 >> 28, k56 & 0xFFFFFFF
    log(f'PC-1 = {k56:014X}; C0 = {c:07X}; D0 = {d:07X}')
    keys = []
    for i, shift in enumerate(SHIFTS, 1):
        c, d = rol28(c, shift), rol28(d, shift)
        subkey = permute((c << 28) | d, PC2, 56)
        keys.append(subkey)
        log(f'K{i:02d}: shift={shift}, C={c:07X}, D={d:07X}, PC-2={subkey:012X}')
    return keys

def feistel(r, k, log=lambda _: None):
    expanded = permute(r, E, 32)
    mixed = expanded ^ k
    log(f'  E(R)       = {expanded:012X}')
    log(f'  E(R) XOR K = {mixed:012X}')
    out = 0
    for i in range(8):
        b = (mixed >> (42-6*i)) & 63
        row = ((b & 32) >> 4) | (b & 1)
        col = (b >> 1) & 15
        v = S[i][row][col]
        log(f'  S{i+1}: input={b:06b}, row={row}, col={col}, output={v:04b}')
        out = (out << 4) | v
    log(f'  S-box      = {out:08X}')
    out = permute(out, P, 32)
    log(f'  P / f      = {out:08X}')
    return out

def crypt(block, key, decrypt=False, log=lambda _: None):
    if len(block) != 8 or len(key) != 8:
        raise ValueError('DES requires an 8-byte block and an 8-byte key')
    x, k = int.from_bytes(block, 'big'), int.from_bytes(key, 'big')
    log(f'DES {"DECRYPT" if decrypt else "ENCRYPT"}: input={x:016X}, key={k:016X}')
    keys = key_schedule(k, log)
    ip = permute(x, IP, 64)
    l, r = ip >> 32, ip & 0xFFFFFFFF
    log(f'IP = {ip:016X}; L0 = {l:08X}; R0 = {r:08X}')
    for i in range(1, 17):
        j = 16-i if decrypt else i-1
        log(f'Round {i:02d}: L_in={l:08X}; R_in={r:08X}; K{j+1:02d}={keys[j]:012X}')
        l, r = r, l ^ feistel(r, keys[j], log)
        log(f'  L{i:02d} = {l:08X}; R{i:02d} = {r:08X}')
    pre = (r << 32) | l
    result = permute(pre, FP, 64)
    log(f'R16 || L16 = {pre:016X}')
    log(f'FP / output = {result:016X}')
    return result.to_bytes(8, 'big')
